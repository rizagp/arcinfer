"""Extracts the codepoint category ranges and whitespace set from llama.cpp's unicode-data.cpp."""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
m = re.search(r"unicode_ranges_flags\s*=\s*\{(.*?)\n\};", src, re.S)
pairs = re.findall(r"\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}", m.group(1))
w = re.search(r"unicode_set_whitespace\s*=\s*\{(.*?)\};", src, re.S)
ws = re.findall(r"0x[0-9A-Fa-f]+", w.group(1))
out = ["// Unicode codepoint categories for the BPE pre-tokenizer, extracted from llama.cpp",
       "// (MIT License, Copyright (c) 2023-2026 The ggml authors). Generated by gen_unicode.py - do not edit.",
       "#pragma once", "#include <cstdint>", "",
       "// flags: 0x02 number (\\p{N}), 0x04 letter (\\p{L}), 0x10 mark (\\p{M}); range i spans [start_i, start_{i+1})",
       f"static const uint32_t kUniRangeStart[{len(pairs)}] = {{"]
for i in range(0, len(pairs), 12):
    out.append("  " + ", ".join(p[0] for p in pairs[i:i + 12]) + ",")
out.append("};")
out.append(f"static const uint16_t kUniRangeFlags[{len(pairs)}] = {{")
for i in range(0, len(pairs), 12):
    out.append("  " + ", ".join(p[1] for p in pairs[i:i + 12]) + ",")
out.append("};")
out.append(f"static const uint32_t kUniWhitespace[{len(ws)}] = {{ " + ", ".join(ws) + " };")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(pairs), "ranges,", len(ws), "whitespace codepoints")
