# Writes src/unicode_ps.h: the code point ranges of Unicode punctuation (\p{P}) and symbols (\p{S}), from Python's
# unicodedata, for the Flint pre-tokenizer (src/tokenizer.h). The letter / number / mark table (unicode_tables.h,
# from llama.cpp) stays as it is for the other models. usage: python tools/gen_unicode_ps.py > src/unicode_ps.h
import sys, unicodedata

starts, flags = [], []
prev = None
for cp in range(0x110000):
    f = 1 if unicodedata.category(chr(cp))[0] in 'PS' else 0
    if f != prev:
        starts.append(cp)
        flags.append(f)
        prev = f
out = open(sys.stdout.fileno(), 'w', newline='\n', closefd=False)  # (LF on Windows too)
out.write('// Unicode punctuation and symbol code points (\\p{P} / \\p{S}) for the Flint pre-tokenizer, Unicode %s\n'
          % unicodedata.unidata_version)
out.write('// (Python unicodedata). Generated by tools/gen_unicode_ps.py - do not edit.\n#pragma once\n#include <cstdint>\n\n')
out.write('// range i spans [kUniPsStart[i], kUniPsStart[i + 1]); kUniPsIs[i]: 1 = punctuation or symbol\n')
out.write('static const uint32_t kUniPsStart[%d] = {\n' % len(starts))
for i in range(0, len(starts), 12):
    out.write('  ' + ', '.join('0x%06X' % s for s in starts[i:i + 12]) + ',\n')
out.write('};\nstatic const uint8_t kUniPsIs[%d] = {\n' % len(flags))
for i in range(0, len(flags), 32):
    out.write('  ' + ', '.join(str(f) for f in flags[i:i + 32]) + ',\n')
out.write('};\n')
